/**
 * Capture the product screenshots the landing page uses.
 *
 * The marketing page shows the real app, not drawings, so these images must be
 * re-captured whenever the UI they show changes.
 *
 *   pnpm db:migrate:local      # once
 *   pnpm seed:marketing        # opportunities, Search Console, saved keywords
 *   pnpm seed:rank-tracking    # rank tracking history
 *   pnpm dev                   # with AUTH_MODE=local_noauth, on PORT 3001
 *   pnpm capture:product
 *
 * Writes WebP into src/public/product/. Commit the results.
 */

import { execFileSync } from "node:child_process";
import { mkdir, rm } from "node:fs/promises";
import process from "node:process";
import { chromium, type Page } from "@playwright/test";
import { parseArgs } from "./cli-utils";

const OUT_DIR = "src/public/product";
// 2x so the images stay sharp on retina displays at their rendered size.
const SCALE = 2;
const VIEWPORT = { width: 1360, height: 850 };

type Shot = {
  /** File name, without extension. */
  name: string;
  /** Path under the project, e.g. "/opportunities". */
  path: string;
  /** Follow the first link matching this accessible name, if present. Used to
   *  reach detail views whose ids are generated by the seed. */
  openFirst?: RegExp;
  /** Extra settle time for pages that animate a chart in. */
  settleMs?: number;
};

// The dashboard is deliberately absent: locally it shows the "Get started"
// checklist and Google OAuth warnings, which are setup state rather than
// product.
const SHOTS: Shot[] = [
  { name: "opportunities", path: "/opportunities", settleMs: 1500 },
  {
    name: "rank-tracking",
    path: "/rank-tracking",
    openFirst: /^Open /,
    settleMs: 2200,
  },
  { name: "saved-keywords", path: "/saved", settleMs: 1200 },
];

async function main() {
  const args = parseArgs(process.argv.slice(2));
  const origin = args.origin ?? "http://localhost:3001";
  await mkdir(OUT_DIR, { recursive: true });

  const browser = await chromium.launch();
  const page = await browser.newPage({
    viewport: VIEWPORT,
    deviceScaleFactor: SCALE,
  });
  // The landing page shows the dark theme, which reads better on the dark hero.
  await page.addInitScript(() =>
    localStorage.setItem("theme-preference", "dark"),
  );

  try {
    await page.goto(`${origin}/app`, {
      waitUntil: "networkidle",
      timeout: 60_000,
    });
    await page.waitForTimeout(4000);
    const projectBase = page.url().replace(/\/$/, "");
    if (!projectBase.includes("/p/")) {
      throw new Error(
        `Expected to land on a project page, got ${page.url()}. Is the dev server running with AUTH_MODE=local_noauth?`,
      );
    }

    for (const shot of SHOTS) {
      await page.goto(`${projectBase}${shot.path}`, {
        waitUntil: "networkidle",
        timeout: 60_000,
      });
      await settle(page, shot.settleMs ?? 1200);
      if (shot.openFirst) {
        const link = page.getByRole("link", { name: shot.openFirst }).first();
        const href = await link.getAttribute("href").catch(() => null);
        if (href) {
          await page.goto(`${origin}${href}`, { waitUntil: "networkidle" });
          await settle(page, shot.settleMs ?? 1200);
        }
      }
      // Playwright writes PNG/JPEG only. JPEG smears UI text, so capture PNG
      // and convert: WebP is about a third of the PNG size at this quality.
      const png = `${OUT_DIR}/${shot.name}.png`;
      const webp = `${OUT_DIR}/${shot.name}.webp`;
      await hideSetupBanners(page);
      await page.screenshot({ path: png });
      toWebp(png, webp);
      await rm(png);
      console.log(`Captured ${webp}`);
    }
  } finally {
    await browser.close();
  }

  console.log("\nDone. Review the images, then commit src/public/product/.");
}

/** cwebp ships with the `webp` package (brew install webp, apt install webp). */
function toWebp(png: string, webp: string) {
  try {
    execFileSync("cwebp", ["-quiet", "-q", "80", png, "-o", webp]);
  } catch (error) {
    const code = (error as NodeJS.ErrnoException).code;
    if (code === "ENOENT") {
      throw new Error(
        "cwebp not found. Install it with `brew install webp` or `apt install webp`.",
      );
    }
    throw error;
  }
}

/**
 * The "add a DataForSEO API key" strip describes this machine's setup, not the
 * product, and would otherwise sit at the top of every image. Run this
 * immediately before the shot: the app re-checks key status after navigation,
 * so an earlier removal can be undone.
 */
async function hideSetupBanners(page: Page) {
  await page.evaluate(() => {
    for (const alert of document.querySelectorAll('[data-slot="alert"]')) {
      if (/DataForSEO|API key/i.test(alert.textContent ?? "")) {
        alert.remove();
      }
    }
  });
  await page.waitForTimeout(250);
}

/** Dismiss transient overlays and let charts finish their entry animation. */
async function settle(page: Page, ms: number) {
  await page.waitForTimeout(ms);
  // Setup prompts and nudges are state, not product: they must not appear in
  // marketing images.
  const dismiss = page.getByRole("button", { name: /^(Dismiss|Not now)$/ });
  if (await dismiss.count()) {
    await dismiss
      .first()
      .click()
      .catch(() => {});
    await page.waitForTimeout(600);
  }
  await page.mouse.move(0, 0);
  await page.waitForTimeout(400);
}

await main();
